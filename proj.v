`timescale 1ns/1ps

module rv32i_cpu_tb;

    reg clk;
    reg reset;

    //----------------------------------------------------------
    // CPU
    //----------------------------------------------------------

    rv32i_cpu uut(
        .clk(clk),
        .reset(reset)
    );

    //----------------------------------------------------------
    // CLOCK
    //----------------------------------------------------------

    always #5 clk = ~clk;

    //----------------------------------------------------------
    // TEST
    //----------------------------------------------------------

    initial begin

        clk = 0;
        reset = 1;

        //------------------------------------------------------
        // RESET
        //------------------------------------------------------

        #20;
        reset = 0;

        //------------------------------------------------------
        // RUN
        //------------------------------------------------------

        #200;

        //------------------------------------------------------
        // FINAL RESULTS
        //------------------------------------------------------

        $display("================================");
        $display("FINAL RESULTS");
        $display("================================");

        $display("x1 = %d", uut.x[1]);
        $display("x2 = %d", uut.x[2]);
        $display("x3 = %d", uut.x[3]);
        $display("x4 = %d", uut.x[4]);
        $display("x5 = %d", uut.x[5]);

        $display("MEM[2] = %d", uut.data_mem[2]);

        $display("================================");

        if(uut.data_mem[2] == 150)
            $display("CPU WORKING CORRECTLY");
        else
            $display("CPU FAILED");

        $finish;

    end

endmodule